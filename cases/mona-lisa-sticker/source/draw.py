def portrait(level):
    drawing = Drawing(level)
    hair_back(drawing)
    garment(drawing)
    bust(drawing)
    face(drawing)
    hands(drawing)
    return drawing.image


def composite(subject, level):
    background = landscape(level)
    outline = Image.new("RGBA", SIZE, COLORS["paper"])
    outline.putalpha(subject.getchannel("A").filter(ImageFilter.MaxFilter(5)))
    background.alpha_composite(outline)
    background.alpha_composite(subject)
    return background


def main():
    build = Path(__file__).resolve().parents[1] / "build"
    steps = build / "steps"
    steps.mkdir(parents=True, exist_ok=True)
    blockin = portrait(1)
