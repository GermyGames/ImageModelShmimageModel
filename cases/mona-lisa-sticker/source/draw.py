class Drawing:
    def __init__(self, level):
        self.level = level
        self.image = Image.new("RGBA", SIZE)
        self.pen = ImageDraw.Draw(self.image)

    def shape(self, color, points, edge=None, level=1):
        if self.level >= level:
            self.pen.polygon(points, COLORS[color], COLORS[edge] if edge else None)

    def line(self, color, points, width=1, level=2):
        if self.level >= level:
            self.pen.line(points, COLORS[color], width)

    def box(self, color, bounds, level=3):
        if self.level >= level:
            self.pen.rectangle(bounds, COLORS[color])


