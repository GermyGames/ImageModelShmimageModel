def build(name):
 p=PALETTES[name]; steps=ROOT/f'pastel-cliffs-{name}'/'build'/'steps'
 for stage,filename in enumerate(('01_silhouette.png','02_blockin.png','03_shading.png','04_cleanup.png')):
  im=Image.new('RGB',(N,N),p[3]); d=ImageDraw.Draw(im)
  for i,s in enumerate(seams):
   draw_shape(d,'p',s,p[1 if i in (1,2,8,10,14) and stage>=2 else 2])
  if stage>=1:
   for face,col in faces: draw_shape(d,'p',face,p[col])
  if stage>=2:
   for i,face in enumerate(accents): draw_shape(d,'p',face,p[5 if i in (1,6,9) else 4])
  if stage>=3:
   for crack in cracks: draw_shape(d,'l',crack,p[1])
  im.save(steps/filename)

