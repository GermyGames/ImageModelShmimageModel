def draw_shape(d,kind,pts,color):
 for dx in (-N,0,N):
  for dy in (-N,0,N):
   p=[(x+dx,y+dy) for x,y in pts]
   if kind=='p': d.polygon(p,fill=color)
   else: d.line(p,fill=color,width=1)

