class Pixels:
    def __init__(self, stage, fill=None):
        self.stage = stage
        self.image = Image.new("RGBA", SIZE, PALETTE[fill] if fill else (0, 0, 0, 0))
        self.pen = ImageDraw.Draw(self.image)

    def shape(self, color, points, border=None, stage=1):
        if self.stage >= stage:
            self.pen.polygon(points, PALETTE[color], PALETTE[border] if border else None)

    def line(self, color, points, stage=2):
        if self.stage >= stage:
            self.pen.line(points, PALETTE[color])

    def dot(self, color, x, y):
        if self.stage >= 3:
            self.pen.point((x, y), PALETTE[color])


