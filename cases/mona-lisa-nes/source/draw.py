def subject(stage):
    c = Pixels(stage)
    clothes_and_hair(c)
    portrait(c)
    folded_hands(c)
    return c.image


def combine(foreground, stage):
    scene = landscape(stage)
    scene.alpha_composite(foreground)
    return scene


def main():
    build = Path(__file__).resolve().parents[1] / "build"
    steps = build / "steps"
    blockin = subject(1)
    silhouette = Image.new("RGBA", SIZE, PALETTE["ink"])
    silhouette.putalpha(blockin.getchannel("A"))
    combine(silhouette, 1).save(steps / "01_silhouette.png")
    combine(blockin, 1).save(steps / "02_blockin.png")
    combine(subject(2), 2).save(steps / "03_shading.png")
    final = combine(subject(3), 3)
    final.save(steps / "04_cleanup.png")
    rgb = np.asarray(final.convert("RGB")).reshape(-1, 3)
    palette, indices = np.unique(rgb, return_inverse=True, axis=0)
    np.save(build / "palette_rgb.npy", palette)
    np.save(build / "final_indices.npy", indices.reshape(SIZE[1], SIZE[0]))


if __name__ == "__main__":
    main()
